def padd(p, q):
    out = dict(p)
    for k, v in q.items():
        out[k] = out.get(k, Fr(0)) + v
    return {k: v for k, v in out.items() if v != 0}


def psub(p, q):
    return padd(p, {k: -v for k, v in q.items()})


def pmul(p, q):
    out = {}
    for a, u in p.items():
        for b, v in q.items():
            k = tuple(x + y for x, y in zip(a, b))
            out[k] = out.get(k, Fr(0)) + u * v
    return {k: v for k, v in out.items() if v != 0}


def psubstitute(p, var, val):
    """honest substitution: p with `var` replaced by the Fraction `val`."""
    ix = IX[var]
    out = {}
    for e, c in p.items():
        e2 = list(e)
        f = c * Fr(val) ** e2[ix]
        e2[ix] = 0
        k = tuple(e2)
        out[k] = out.get(k, Fr(0)) + f
    return {k: v for k, v in out.items() if v != 0}


def pflip(p, var):
    """symbolic substitution var -> -var."""
    ix = IX[var]
    out = {}
    for e, c in p.items():
        out[e] = c * ((-1) ** e[ix])
    return {k: v for k, v in out.items() if v != 0}


